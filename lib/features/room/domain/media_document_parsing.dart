import 'dart:convert';

import 'package:flutter/foundation.dart';

/// Parsers for server-, provider- and peer-supplied media documents
/// (subtitles, danmaku). Every parse in this library is linear in the
/// document size and every document is capped, so a hostile document degrades
/// to a missing track instead of freezing the UI isolate.

/// Documents larger than this are rejected at fetch time. Real subtitle and
/// danmaku documents stay far below it.
const maxSubtitleDocumentBytes = 8 * 1024 * 1024;
const maxDanmakuDocumentBytes = 8 * 1024 * 1024;

/// Post-decode caps applied before parsing; UTF-16 code units approximate the
/// decoded byte budget closely enough for rejection.
const maxSubtitleDocumentChars = maxSubtitleDocumentBytes;
const maxDanmakuDocumentChars = maxDanmakuDocumentBytes;

/// Item caps so a pathological document cannot trade bytes for item counts.
const _maxSubtitleCues = 200000;
const _maxDanmakuItems = 100000;

/// One subtitle track cue.
class SubtitleCue {
  const SubtitleCue(this.start, this.end, this.text);

  final Duration start;
  final Duration end;
  final String text;
}

/// Placement shared by the danmaku sources.
enum DanmakuPlacement { floating, top, bottom }

/// One danmaku comment parsed from a document. Presentation maps this onto
/// the widget model.
class DanmakuRecord {
  const DanmakuRecord({
    required this.text,
    required this.start,
    required this.end,
    required this.colorRgb,
    required this.placement,
  });

  final String text;
  final Duration start;
  final Duration end;

  /// 24-bit decimal RGB value.
  final int colorRgb;
  final DanmakuPlacement placement;
}

/// Result of parsing a subtitle document.
class SubtitleDocument {
  const SubtitleDocument({this.cues = const [], this.danmaku = const []});

  /// A danmu2ass script renders as danmaku instead of a subtitle track.
  bool get isDanmaku => danmaku.isNotEmpty;

  final List<SubtitleCue> cues;
  final List<DanmakuRecord> danmaku;
}

/// Parses a subtitle document: bilibili JSON (only when [format] is `json`),
/// ASS (including danmu2ass scripts), or SRT/VTT cue syntax.
SubtitleDocument parseSubtitleDocument(String content, {String? format}) {
  if (_parseBilibiliJsonSubtitleCues(content, format: format)
      case final cues?) {
    return SubtitleDocument(cues: cues);
  }
  final isAss =
      content.contains('[Script Info]') || content.contains('[Events]');
  if (!isAss) {
    return SubtitleDocument(cues: parseCueDocument(content));
  }
  if (content.contains('Script generated by danmu2ass')) {
    return SubtitleDocument(danmaku: _parseAssDialogueRecords(content));
  }
  return SubtitleDocument(cues: _parseAssSubtitleCues(content));
}

/// Isolate-friendly entry point: bytes in, parsed document out.
SubtitleDocument parseSubtitleDocumentBytes(SubtitleParseRequest request) {
  if (request.bytes.length > maxSubtitleDocumentBytes) {
    throw const FormatException('subtitle document exceeds size cap');
  }
  return parseSubtitleDocument(
    decodeSubtitleDocumentBytes(request.bytes),
    format: request.format,
  );
}

/// Input to [parseSubtitleDocumentBytes].
class SubtitleParseRequest {
  const SubtitleParseRequest({required this.bytes, this.format});

  final Uint8List bytes;
  final String? format;
}

/// Runs document parsing off the UI isolate. Production uses [compute]; tests
/// replace it with an inline runner because spawned isolates never complete
/// inside fake async.
Future<R> Function<Q, R>(R Function(Q) callback, Q message)
documentParseRunner = compute;

/// Decodes subtitle bytes, honouring UTF-8/UTF-16 byte-order marks.
String decodeSubtitleDocumentBytes(Uint8List bytes) {
  if (bytes.length >= 2 && bytes[0] == 0xFF && bytes[1] == 0xFE) {
    return _decodeUtf16(bytes, offset: 2, littleEndian: true);
  }
  if (bytes.length >= 2 && bytes[0] == 0xFE && bytes[1] == 0xFF) {
    return _decodeUtf16(bytes, offset: 2, littleEndian: false);
  }
  final start =
      bytes.length >= 3 &&
          bytes[0] == 0xEF &&
          bytes[1] == 0xBB &&
          bytes[2] == 0xBF
      ? 3
      : 0;
  try {
    return utf8.decode(bytes.sublist(start), allowMalformed: false);
  } on FormatException {
    return utf8.decode(bytes.sublist(start), allowMalformed: true);
  }
}

String _decodeUtf16(
  Uint8List bytes, {
  required int offset,
  required bool littleEndian,
}) {
  final codes = <int>[];
  for (var i = offset; i + 1 < bytes.length; i += 2) {
    codes.add(
      littleEndian
          ? bytes[i] | (bytes[i + 1] << 8)
          : (bytes[i] << 8) | bytes[i + 1],
    );
  }
  return String.fromCharCodes(codes);
}

/// Removes WebVTT inline timing and style tags and tidies cue text.
String sanitizeSubtitleText(String text) {
  return text
      .replaceAll(RegExp(r'<(?:\d{2}:)?\d{2}:\d{2}[.,]\d{3}>'), '')
      .replaceAll(RegExp(r'<[^>]+>'), '')
      .replaceAll('&nbsp;', ' ')
      .replaceAll('&amp;', '&')
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>')
      .split('\n')
      .map((line) => line.trim())
      .where((line) => line.isNotEmpty)
      .join('\n');
}

/// Removes `{...}` override tags in one pass. Unlike a lazy regex this does
/// not rescan the tail from every unclosed brace, so brace-heavy text stays
/// linear; an unterminated tag is preserved rather than swallowing the rest.
String stripAssTags(String text) {
  final open = text.indexOf('{');
  if (open == -1) return text;
  final buffer = StringBuffer()..write(text.substring(0, open));
  var index = open;
  while (index < text.length) {
    if (text.codeUnitAt(index) == 0x7B /* { */ ) {
      final close = text.indexOf('}', index + 1);
      if (close == -1) {
        buffer.write(text.substring(index));
        break;
      }
      index = close + 1;
    } else {
      final next = text.indexOf('{', index + 1);
      if (next == -1) {
        buffer.write(text.substring(index));
        break;
      }
      buffer.write(text.substring(index, next));
      index = next;
    }
  }
  return buffer.toString();
}

/// Parses SRT/WebVTT cue documents.
List<SubtitleCue> parseCueDocument(String content) {
  final lines = LineSplitter.split(content).toList(growable: false);
  final cueRegex = RegExp(
    r'((?:\d{2}:)?\d{2}:\d{2}[.,]\d{3}) --> ((?:\d{2}:)?\d{2}:\d{2}[.,]\d{3})',
  );
  final cues = <SubtitleCue>[];
  for (var i = 0; i < lines.length && cues.length < _maxSubtitleCues; i++) {
    final match = cueRegex.firstMatch(lines[i].trim());
    if (match == null) continue;
    final start = parseCueTimestamp(match.group(1)!);
    final end = parseCueTimestamp(match.group(2)!);
    if (start == null || end == null) continue;
    final textLines = <String>[];
    var j = i + 1;
    while (j < lines.length && lines[j].trim().isNotEmpty) {
      textLines.add(lines[j].trim());
      j++;
    }
    i = j;
    final text = sanitizeSubtitleText(textLines.join('\n'));
    if (text.isNotEmpty) {
      cues.add(SubtitleCue(start, end, text));
    }
  }
  return cues;
}

/// Parses bilibili `<d p="...">` danmaku XML in a single index walk; the
/// historical lazy-quantifier regex rescanned the document tail once per
/// unclosed start tag and froze the UI isolate on hostile input.
List<DanmakuRecord> parseBilibiliDanmakuXml(String content) {
  final normalized = content
      .replaceAll('\u00A0', ' ')
      .replaceAll('\u3000', ' ')
      .replaceAll(RegExp(r'\s+'), ' ');
  final items = <DanmakuRecord>[];
  var search = 0;
  while (items.length < _maxDanmakuItems) {
    final dialogue = _nextDanmakuDialogue(normalized, search);
    if (dialogue == null) break;
    search = dialogue.end;
    final record = _danmakuRecordFromAttributes(
      dialogue.attributes,
      dialogue.text,
    );
    if (record != null) {
      items.add(record);
    }
  }
  return items;
}

class _DanmakuDialogue {
  const _DanmakuDialogue(this.attributes, this.text, this.end);

  final String attributes;
  final String text;
  final int end;
}

_DanmakuDialogue? _nextDanmakuDialogue(String source, int from) {
  var index = from;
  while (true) {
    final start = source.indexOf('<d', index);
    if (start == -1) return null;
    var cursor = _skipWhitespace(source, start + 2);
    if (!_consume(source, cursor, 'p')) {
      index = start + 1;
      continue;
    }
    cursor = _skipWhitespace(source, cursor + 1);
    if (!_consume(source, cursor, '=')) {
      index = start + 1;
      continue;
    }
    cursor = _skipWhitespace(source, cursor + 1);
    if (cursor >= source.length || source.codeUnitAt(cursor) != 0x22 /* " */ ) {
      index = start + 1;
      continue;
    }
    final attributesStart = cursor + 1;
    final attributesEnd = source.indexOf('"', attributesStart);
    if (attributesEnd == -1) return null;
    cursor = _skipWhitespace(source, attributesEnd + 1);
    if (cursor >= source.length || source.codeUnitAt(cursor) != 0x3E /* > */ ) {
      index = attributesEnd;
      continue;
    }
    final textStart = cursor + 1;
    final textEnd = source.indexOf('</d>', textStart);
    if (textEnd == -1) return null;
    return _DanmakuDialogue(
      source.substring(attributesStart, attributesEnd),
      source.substring(textStart, textEnd),
      textEnd + 4,
    );
  }
}

DanmakuRecord? _danmakuRecordFromAttributes(String attributes, String rawText) {
  final parts = attributes.split(',');
  if (parts.isEmpty) return null;
  final startSeconds = double.tryParse(parts[0]);
  if (startSeconds == null || startSeconds < 0) return null;
  final mode = parts.length > 1 ? int.tryParse(parts[1]) ?? 1 : 1;
  final color = parts.length > 3
      ? int.tryParse(parts[3]) ?? 0xFFFFFF
      : 0xFFFFFF;
  final placement = switch (mode) {
    4 => DanmakuPlacement.bottom,
    5 => DanmakuPlacement.top,
    _ => DanmakuPlacement.floating,
  };
  final text = _unescapeXmlEntities(rawText).trim();
  if (text.isEmpty) return null;
  final start = Duration(milliseconds: (startSeconds * 1000).toInt());
  return DanmakuRecord(
    text: text,
    start: start,
    end:
        start +
        (placement == DanmakuPlacement.floating
            ? const Duration(seconds: 8)
            : const Duration(seconds: 4)),
    colorRgb: color & 0xFFFFFF,
    placement: placement,
  );
}

String _unescapeXmlEntities(String text) {
  return text
      .replaceAll('&amp;', '&')
      .replaceAll('&lt;', '<')
      .replaceAll('&gt;', '>');
}

List<SubtitleCue>? _parseBilibiliJsonSubtitleCues(
  String content, {
  String? format,
}) {
  if (format?.trim().toLowerCase() != 'json') return null;
  try {
    final decoded = jsonDecode(content);
    if (decoded is! Map || decoded['body'] is! List) return null;
    final cues = <SubtitleCue>[];
    for (final value in decoded['body'] as List) {
      if (value is! Map) continue;
      final startSeconds = _subtitleSeconds(value['from']);
      final endSeconds = _subtitleSeconds(value['to']);
      final text = sanitizeSubtitleText(value['content']?.toString() ?? '');
      if (startSeconds == null ||
          endSeconds == null ||
          endSeconds < startSeconds ||
          text.isEmpty) {
        continue;
      }
      cues.add(
        SubtitleCue(
          Duration(milliseconds: (startSeconds * 1000).round()),
          Duration(milliseconds: (endSeconds * 1000).round()),
          text,
        ),
      );
    }
    return cues;
  } on FormatException {
    return null;
  }
}

double? _subtitleSeconds(Object? value) => switch (value) {
  num value => value.toDouble(),
  String value => double.tryParse(value),
  _ => null,
};

class _AssDialogue {
  const _AssDialogue(this.start, this.end, this.style, this.text);

  final Duration start;
  final Duration end;
  final String style;
  final String text;
}

/// Extracts Dialogue lines from an ASS document, sharing one linear walker
/// between the subtitle and danmu2ass interpretations.
List<_AssDialogue> _parseAssDialogues(String content) {
  final lines = LineSplitter.split(content);
  var formatFields = const <String>[];
  var inEvents = false;
  final dialogues = <_AssDialogue>[];
  for (final rawLine in lines) {
    final line = rawLine.trim();
    if (line == '[Events]') {
      inEvents = true;
      continue;
    }
    if (!inEvents) continue;
    if (line.startsWith('Format:')) {
      formatFields = line
          .substring(7)
          .split(',')
          .map((field) => field.trim().toLowerCase())
          .toList(growable: false);
      continue;
    }
    if (!line.startsWith('Dialogue:')) continue;
    final fields = formatFields.isEmpty
        ? _defaultAssFormatFields
        : formatFields;
    final values = _splitAssFields(line.substring(9).trim(), fields.length);
    if (values.length != fields.length) continue;
    final startIndex = fields.indexOf('start');
    final endIndex = fields.indexOf('end');
    final textIndex = fields.indexOf('text');
    final styleIndex = fields.indexOf('style');
    if (startIndex == -1 || endIndex == -1 || textIndex == -1) continue;
    final start = parseAssDuration(values[startIndex]);
    final end = parseAssDuration(values[endIndex]);
    if (start == null || end == null) continue;
    dialogues.add(
      _AssDialogue(
        start,
        end,
        styleIndex == -1 ? '' : values[styleIndex],
        values[textIndex],
      ),
    );
    if (dialogues.length >= _maxDanmakuItems) break;
  }
  return dialogues;
}

const _defaultAssFormatFields = [
  'layer',
  'start',
  'end',
  'style',
  'name',
  'marginl',
  'marginr',
  'marginv',
  'effect',
  'text',
];

/// Splits an ASS Dialogue payload on commas, keeping the final field intact.
List<String> _splitAssFields(String payload, int fieldCount) {
  final values = <String>[];
  var start = 0;
  for (var i = 0; i < fieldCount - 1; i++) {
    final comma = payload.indexOf(',', start);
    if (comma == -1) return values;
    values.add(payload.substring(start, comma));
    start = comma + 1;
  }
  values.add(start <= payload.length ? payload.substring(start) : '');
  return values;
}

List<SubtitleCue> _parseAssSubtitleCues(String content) {
  final cues = <SubtitleCue>[];
  for (final dialogue in _parseAssDialogues(content)) {
    final text = stripAssTags(dialogue.text).replaceAll(r'\N', '\n').trim();
    if (text.isNotEmpty && cues.length < _maxSubtitleCues) {
      cues.add(SubtitleCue(dialogue.start, dialogue.end, text));
    }
  }
  return cues;
}

List<DanmakuRecord> _parseAssDialogueRecords(String content) {
  final records = <DanmakuRecord>[];
  final colorRegex = RegExp(r'\\c&H([0-9a-fA-F]{6})&');
  for (final dialogue in _parseAssDialogues(content)) {
    final text = stripAssTags(dialogue.text).replaceAll(r'\N', '\n').trim();
    if (text.isEmpty) continue;
    var color = 0xFFFFFF;
    final colorMatch = colorRegex.firstMatch(dialogue.text);
    if (colorMatch != null) {
      final hex = colorMatch.group(1)!; // BBGGRR
      final blue = hex.substring(0, 2);
      final green = hex.substring(2, 4);
      final red = hex.substring(4, 6);
      color = int.parse(red + green + blue, radix: 16);
    }
    final style = dialogue.style.toLowerCase();
    final placement = style.contains('top')
        ? DanmakuPlacement.top
        : style.contains('bottom')
        ? DanmakuPlacement.bottom
        : DanmakuPlacement.floating;
    records.add(
      DanmakuRecord(
        text: text,
        start: dialogue.start,
        end: dialogue.end,
        colorRgb: color,
        placement: placement,
      ),
    );
  }
  return records;
}

/// Parses `h:mm:ss.cc` ASS timestamps; returns null instead of throwing.
Duration? parseAssDuration(String value) {
  final parts = value.trim().split(':');
  if (parts.length != 3) return null;
  final hours = int.tryParse(parts[0]);
  final minutes = int.tryParse(parts[1]);
  if (hours == null || minutes == null) return null;
  final secondParts = parts[2].split('.');
  final seconds = int.tryParse(secondParts[0]);
  final centiseconds = secondParts.length > 1
      ? int.tryParse(secondParts[1])
      : 0;
  if (seconds == null || centiseconds == null) return null;
  return Duration(
    hours: hours,
    minutes: minutes,
    seconds: seconds,
    milliseconds: centiseconds * 10,
  );
}

/// Parses `(hh:)mm:ss[.,]mmm` cue timestamps; returns null instead of throwing.
Duration? parseCueTimestamp(String value) {
  final parts = value.trim().split(':');
  if (parts.length != 2 && parts.length != 3) return null;
  var hours = 0;
  var index = 0;
  if (parts.length == 3) {
    final parsedHours = int.tryParse(parts[0]);
    if (parsedHours == null) return null;
    hours = parsedHours;
    index = 1;
  }
  final minutes = int.tryParse(parts[index]);
  if (minutes == null) return null;
  final secondParts = parts[index + 1].split(RegExp(r'[.,]'));
  if (secondParts.length != 2) return null;
  final seconds = int.tryParse(secondParts[0]);
  if (seconds == null) return null;
  final milliseconds = int.tryParse(secondParts[1]);
  if (milliseconds == null) return null;
  return Duration(
    hours: hours,
    minutes: minutes,
    seconds: seconds,
    milliseconds: milliseconds,
  );
}

int _skipWhitespace(String source, int index) {
  while (index < source.length && _isXmlWhitespace(source.codeUnitAt(index))) {
    index++;
  }
  return index;
}

bool _isXmlWhitespace(int codeUnit) =>
    codeUnit == 0x20 ||
    codeUnit == 0x09 ||
    codeUnit == 0x0A ||
    codeUnit == 0x0D;

bool _consume(String source, int index, String expected) {
  if (index + expected.length > source.length) return false;
  for (var i = 0; i < expected.length; i++) {
    if (source.codeUnitAt(index + i) != expected.codeUnitAt(i)) return false;
  }
  return true;
}
