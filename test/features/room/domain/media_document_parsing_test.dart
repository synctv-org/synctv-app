import 'dart:convert';

import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:synctv_app/features/room/domain/media_document_parsing.dart';

void main() {
  group('stripAssTags', () {
    test('matches the historical lazy-regex behavior', () {
      // Regression parity with text.replaceAll(RegExp(r'\{.*?\}'), '').
      final cases = [
        'plain',
        '{\\pos(1,2)}tagged',
        'a{b}c{d}e',
        '{{{{a}}',
        'unterminated{abc',
        'a{b}c{d',
        '{}{}',
        '{\\c&HFFFFFF&}{\\b1}text',
      ];
      final historical = RegExp(r'\{.*?\}');
      for (final value in cases) {
        expect(
          stripAssTags(value),
          value.replaceAll(historical, ''),
          reason: value,
        );
      }
    });

    test('stays linear on brace-heavy hostile text', () {
      final hostile = '{' * 200000; // ~200KB of unclosed braces
      final watch = Stopwatch()..start();
      final result = stripAssTags(hostile);
      watch.stop();
      expect(result.length, hostile.length);
      expect(watch.elapsed, lessThan(const Duration(seconds: 2)));
    });
  });

  group('parseSubtitleDocument', () {
    test('parses ASS dialogue cues with format fields and tag stripping', () {
      const content = '''
[Script Info]
Title: test
[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\\pos(1,2)}Hello\\Nworld
''';
      final document = parseSubtitleDocument(content);
      expect(document.isDanmaku, isFalse);
      expect(document.cues, hasLength(1));
      expect(document.cues.single.start, const Duration(seconds: 1));
      expect(document.cues.single.end, const Duration(seconds: 2));
      expect(document.cues.single.text, 'Hello\nworld');
    });

    test('skips dialogue lines with malformed timestamps', () {
      const content = '''
[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,bad,0:00:02.00,Default,,0,0,0,,one
Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,two
''';
      final document = parseSubtitleDocument(content);
      expect(document.cues.map((cue) => cue.text), ['two']);
    });

    test('treats a danmu2ass script as danmaku with color and placement', () {
      const content = '''
[Script Info]
Script generated by danmu2ass
[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
Dialogue: 0,0:00:01.00,0:00:05.00,Top,,0,0,0,,{\\c&HFF0000&}red top
Dialogue: 0,0:00:02.00,0:00:06.00,bottom,,0,0,0,,bottom line
Dialogue: 0,0:00:03.00,0:00:07.00,Default,,0,0,0,,floating
''';
      final document = parseSubtitleDocument(content);
      expect(document.isDanmaku, isTrue);
      expect(document.danmaku, hasLength(3));
      // \c&HFF0000& is BGR: blue=FF green=00 red=00 -> RGB 0x0000FF.
      expect(document.danmaku[0].colorRgb, 0x0000FF);
      expect(document.danmaku[0].placement, DanmakuPlacement.top);
      expect(document.danmaku[1].placement, DanmakuPlacement.bottom);
      expect(document.danmaku[2].placement, DanmakuPlacement.floating);
      expect(document.danmaku[0].text, 'red top');
    });

    test('parses SRT cue documents', () {
      const content = '''
1
00:00:01,000 --> 00:00:02,000
first line
second line

2
00:00:03.500 --> 00:00:04,000
timed
''';
      final document = parseSubtitleDocument(content);
      expect(document.cues, hasLength(2));
      expect(document.cues[0].start, const Duration(seconds: 1));
      expect(document.cues[0].text, 'first line\nsecond line');
      expect(document.cues[1].start, const Duration(milliseconds: 3500));
    });

    test('parses bilibili JSON bodies only for the json format', () {
      const content = '{"body":[{"from":1.5,"to":2.5,"content":"hi"}]}';
      expect(parseSubtitleDocument(content).cues, isEmpty);
      final document = parseSubtitleDocument(content, format: 'json');
      expect(document.cues, hasLength(1));
      expect(document.cues.single.text, 'hi');
      expect(document.cues.single.start, const Duration(milliseconds: 1500));
    });

    test('stays linear on hostile brace-heavy ASS text', () {
      final hostile =
          '[Events]\n'
          'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n'
          'Dialogue: 0,0:00:01.00,0:00:59.00,Default,,0,0,0,,'
          '${'{' * 100000}\n';
      final watch = Stopwatch()..start();
      final document = parseSubtitleDocument(hostile);
      watch.stop();
      // Unclosed braces survive tag stripping (matching the historical
      // regex), but the parse itself must stay linear.
      expect(document.cues, hasLength(1));
      expect(document.cues.single.text, isNotEmpty);
      expect(watch.elapsed, lessThan(const Duration(seconds: 2)));
    });

    test('stays linear on hostile cue accumulation', () {
      final body = List.filled(100000, 'a' * 20).join('\n');
      final content = '1\n00:00:01,000 --> 00:00:59,000\n$body\n';
      final watch = Stopwatch()..start();
      final document = parseSubtitleDocument(content);
      watch.stop();
      expect(document.cues, hasLength(1));
      expect(watch.elapsed, lessThan(const Duration(seconds: 2)));
    });
  });

  group('parseBilibiliDanmakuXml', () {
    test('parses attributes, placements, colors and entities', () {
      const content =
          '<d p="1.5,1,25,16711680,user">hello &amp; bye</d>'
          '<d p="2.0,4,25,16777215">bottom</d>'
          '<d p="3.0,5,25,16777215">top</d>';
      final items = parseBilibiliDanmakuXml(content);
      expect(items, hasLength(3));
      expect(items[0].text, 'hello & bye');
      expect(items[0].start, const Duration(milliseconds: 1500));
      expect(items[0].end, const Duration(milliseconds: 9500));
      expect(items[0].colorRgb, 0xFF0000);
      expect(items[1].placement, DanmakuPlacement.bottom);
      expect(items[2].placement, DanmakuPlacement.top);
    });

    test('tolerates whitespace between the tag and attribute', () {
      const content = '<i><d\n p="1.0,1,25,16777215">\nspaced\n</d></i>';
      final items = parseBilibiliDanmakuXml(content);
      expect(items.map((item) => item.text), ['spaced']);
    });

    test('stays linear on nested unclosed start tags', () {
      final hostile = '<d p="1,1,25,16777215">' * 50000;
      final watch = Stopwatch()..start();
      final items = parseBilibiliDanmakuXml(hostile);
      watch.stop();
      // No closing tags: zero items, but the scan must complete in linear
      // time instead of freezing the isolate.
      expect(items, isEmpty);
      expect(watch.elapsed, lessThan(const Duration(seconds: 2)));
    });

    test('stays linear on a large closed document', () {
      final hostile = '<d p="1,1,25,16777215">x</d>' * 50000; // ~1.4MB
      final watch = Stopwatch()..start();
      final items = parseBilibiliDanmakuXml(hostile);
      watch.stop();
      expect(items, hasLength(50000));
      expect(watch.elapsed, lessThan(const Duration(seconds: 5)));
    });
  });

  group('decodeSubtitleDocumentBytes', () {
    for (final entry in {
      'utf8': utf8.encode('héllo'),
      'utf8-bom': [0xEF, 0xBB, 0xBF, ...utf8.encode('héllo')],
      'utf16le': [0xFF, 0xFE, ..._utf16CodeUnits('héllo', littleEndian: true)],
      'utf16be': [0xFE, 0xFF, ..._utf16CodeUnits('héllo', littleEndian: false)],
      'malformed-utf8': [0xEF, 0xBB, 0xBF, 0xFF, 0xFE, 0x41],
    }.entries) {
      test('decodes ${entry.key}', () {
        expect(
          decodeSubtitleDocumentBytes(Uint8List.fromList(entry.value)),
          isA<String>(),
        );
      });
    }

    test('round-trips plain utf-8', () {
      expect(
        decodeSubtitleDocumentBytes(Uint8List.fromList(utf8.encode('普通字'))),
        '普通字',
      );
    });
  });

  group('parseSubtitleDocumentBytes', () {
    test('rejects oversized documents', () {
      final oversized = Uint8List(maxSubtitleDocumentBytes + 1);
      expect(
        () =>
            parseSubtitleDocumentBytes(SubtitleParseRequest(bytes: oversized)),
        throwsA(isA<FormatException>()),
      );
    });
  });
}

List<int> _utf16CodeUnits(String text, {required bool littleEndian}) {
  final units = text.codeUnits;
  return [
    for (final unit in units)
      ...(() {
        final high = (unit >> 8) & 0xFF;
        final low = unit & 0xFF;
        return littleEndian ? [low, high] : [high, low];
      })(),
  ];
}
